import { readFile, readdir, mkdir, writeFile, unlink } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultRoot = fileURLToPath(new URL('../', import.meta.url));
const site = 'https://gudu.blog';
const generated = '<!-- Generated by scripts/build-blog.mjs. Edit content/posts instead. -->';
const categories = { '技术': 'tech', '设计': 'design', '随笔': 'notes' };
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const jsonForHTML = value => JSON.stringify(value).replace(/</g, '\\u003c');
const postURL = post => `${site}/posts/${post.slug}.html`;
const displayDate = date => date.replaceAll('-', '.');
const textValue = (value, name) => {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`${name} 必须是非空字符串。`);
  return value.trim();
};

function validateBlock(block, path) {
  if (!block || typeof block !== 'object') throw new Error(`${path} 必须是内容对象。`);
  if (['paragraph', 'quote', 'callout'].includes(block.type)) {
    return { type: block.type, text: textValue(block.text, `${path}.text`) };
  }
  if (block.type === 'list') {
    if (!Array.isArray(block.items) || !block.items.length) throw new Error(`${path}.items 需要至少一条文字。`);
    return { type: 'list', ordered: block.ordered === true, items: block.items.map((item, i) => textValue(item, `${path}.items[${i}]`)) };
  }
  if (block.type === 'code') {
    textValue(block.code, `${path}.code`);
    return { type: 'code', language: typeof block.language === 'string' ? block.language.trim() : '', code: block.code };
  }
  throw new Error(`${path}.type 不支持：${block.type}。可用 paragraph / list / code / quote / callout。`);
}

function normalizePost(value, filename) {
  if (!value || typeof value !== 'object') throw new Error(`${filename} 必须包含文章对象。`);
  const slug = textValue(value.slug, `${filename}.slug`);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error(`${filename}.slug 只能使用小写英文字母、数字和中间的连字符。`);
  const date = textValue(value.date, `${filename}.date`);
  const parsedDate = new Date(`${date}T00:00:00Z`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || Number.isNaN(parsedDate.valueOf()) || parsedDate.toISOString().slice(0, 10) !== date) throw new Error(`${filename}.date 需要有效的 YYYY-MM-DD 日期。`);
  const category = textValue(value.category, `${filename}.category`);
  const tags = value.tags ?? [];
  if (!Array.isArray(tags)) throw new Error(`${filename}.tags 必须是字符串数组。`);
  if (!Array.isArray(value.sections) || !value.sections.length) throw new Error(`${filename}.sections 需要至少一个章节。`);
  const ids = new Set(['main-content']);
  const sections = value.sections.map((section, i) => {
    const path = `${filename}.sections[${i}]`;
    if (!section || typeof section !== 'object') throw new Error(`${path} 必须是章节对象。`);
    const id = section.id ?? `section-${i + 1}`;
    if (id === 'main-content') throw new Error(`${path}.id 的 main-content 是页面保留锚点，请使用其他唯一的小写英文锚点。`);
    if (typeof id !== 'string' || !/^[a-z][a-z0-9-]*$/.test(id) || ids.has(id)) throw new Error(`${path}.id 需要唯一的小写英文锚点，以字母开头。`);
    ids.add(id);
    if (!Array.isArray(section.blocks) || !section.blocks.length) throw new Error(`${path}.blocks 需要至少一个内容块。`);
    return { id, title: textValue(section.title, `${path}.title`), blocks: section.blocks.map((block, j) => validateBlock(block, `${path}.blocks[${j}]`)) };
  });
  for (const key of ['draft', 'demo', 'featured']) {
    if (value[key] !== undefined && typeof value[key] !== 'boolean') throw new Error(`${filename}.${key} 必须是布尔值。`);
  }
  const title = textValue(value.title, `${filename}.title`);
  const excerpt = textValue(value.excerpt ?? value.summary, `${filename}.excerpt`);
  const plainText = [title, excerpt, ...sections.flatMap(section => [section.title, ...section.blocks.flatMap(block => block.text ?? block.code ?? block.items)])].join(' ');
  const chineseCharacters = (plainText.match(/[\u3400-\u9fff]/g) ?? []).length;
  const words = (plainText.replace(/[\u3400-\u9fff]/g, ' ').match(/\S+/g) ?? []).length;
  return {
    id: slug, slug, title, excerpt, summary: excerpt, category,
    categorySlug: categories[category] ?? 'other',
    tags: [...new Set(tags.map((tag, i) => textValue(tag, `${filename}.tags[${i}]`)))],
    date, readingMinutes: Math.max(1, Math.ceil(chineseCharacters / 350 + words / 200)),
    url: `./posts/${slug}.html`, demo: value.demo === true, featured: value.featured === true,
    draft: value.draft === true, sections,
  };
}

function renderBlock(block) {
  if (block.type === 'paragraph') return `<p>${escape(block.text)}</p>`;
  if (block.type === 'quote') return `<blockquote><p>${escape(block.text)}</p></blockquote>`;
  if (block.type === 'callout') return `<aside class="article-callout"><p>${escape(block.text)}</p></aside>`;
  if (block.type === 'list') {
    const tag = block.ordered ? 'ol' : 'ul';
    return `<${tag}>${block.items.map(item => `<li>${escape(item)}</li>`).join('')}</${tag}>`;
  }
  return `<div class="code-block">${block.language ? `<span class="code-language">${escape(block.language)}</span>` : ''}<pre><code>${escape(block.code)}</code></pre></div>`;
}

function siteHeader(prefix) {
  return `<a class="skip-link" href="#main-content">跳到主要内容</a>
    <header class="site-header">
      <a class="site-brand" href="${prefix}index.html#home" aria-label="Gudu 博客首页"><img class="brand-logo" src="${prefix}assets/brand/gudu-logo-light.svg?v=20261018-logo" width="56" height="56" alt="GUDU" /></a>
      <nav class="site-nav" aria-label="主导航">
        <a href="${prefix}index.html#journal">文章</a><a href="${prefix}index.html#archive">归档</a><a href="${prefix}index.html#about">关于</a>
      </nav>
      <a class="header-rss" href="${prefix}feed.xml" aria-label="RSS 订阅">RSS <span aria-hidden="true">↗</span></a>
    </header>`;
}

function siteFooter(prefix) {
  return `<footer class="site-footer"><a class="footer-brand" href="${prefix}index.html#home"><img class="brand-logo" src="${prefix}assets/brand/gudu-logo-light.svg?v=20261018-logo" width="56" height="56" alt="GUDU" /></a><p>在自己的轨道上，保持好奇。</p><a href="${prefix}feed.xml">RSS 订阅 <span aria-hidden="true">↗</span></a></footer>`;
}

function documentHead({ title, description, canonical, prefix, noindex = false, article }) {
  return `<meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#080b10" />
    <meta name="description" content="${escape(description)}" />
    ${noindex ? '<meta name="robots" content="noindex, follow" />' : ''}
    <title>${escape(title)}</title>
    <link rel="canonical" href="${escape(canonical)}" />
    <meta property="og:type" content="${article ? 'article' : 'website'}" />
    <meta property="og:site_name" content="Gudu 的个人博客" />
    <meta property="og:locale" content="zh_CN" />
    <meta property="og:title" content="${escape(title)}" />
    <meta property="og:description" content="${escape(description)}" />
    <meta property="og:url" content="${escape(canonical)}" />
    ${article ? `<meta property="article:published_time" content="${article.date}T00:00:00Z" />` : ''}
    <link rel="icon" type="image/svg+xml" href="${prefix}assets/favicon.svg?v=20261018-logo" />
    <link rel="alternate" type="application/rss+xml" title="Gudu 的个人博客" href="${prefix}feed.xml" />
    <link rel="stylesheet" href="${prefix}css/style.css" />
    <link rel="stylesheet" href="${prefix}css/blog.css?v=20261018-logo" />`.replace(/[ \t]+$/gm, '');
}

function renderArticle(post, index, posts) {
  const newer = posts[index - 1];
  const older = posts[index + 1];
  const postLink = (item, className, label, arrow) => item ? `<a class="${className}" href="./${item.slug}.html"><span>${label} ${arrow}</span><strong>${escape(item.title)}</strong></a>` : `<span class="${className} is-unavailable"><span>${label}</span><strong>已到达这一端</strong></span>`;
  const structuredData = post.demo ? '' : `<script type="application/ld+json">${jsonForHTML({ '@context': 'https://schema.org', '@type': 'BlogPosting', headline: post.title, description: post.excerpt, datePublished: post.date, mainEntityOfPage: postURL(post), inLanguage: 'zh-CN' })}</script>`;
  return `<!doctype html>
${generated}
<html lang="zh-CN">
  <head>
    ${documentHead({ title: `${post.title} · Gudu 的个人博客`, description: post.excerpt, canonical: postURL(post), prefix: '../', noindex: post.demo, article: post })}
${structuredData}
    <script src="../js/article.js" defer></script>
  </head>
  <body class="article-page">
    <div class="reading-progress" aria-hidden="true" hidden><span data-reading-progress></span></div>
    ${siteHeader('../')}
    <main class="article-shell" id="main-content" tabindex="-1">
      <a class="article-back" href="../index.html#journal"><span aria-hidden="true">←</span> 返回文章列表</a>
      <header class="article-header">
        <p class="eyebrow">${escape(post.category)} <span aria-hidden="true">/</span> FIELD NOTES</p>
        <div class="article-meta"><time datetime="${post.date}">${displayDate(post.date)}</time><span>约 ${post.readingMinutes} 分钟阅读</span>${post.demo ? '<span>示例文章</span>' : ''}</div>
        <h1 class="article-title">${escape(post.title)}</h1>
        <p class="article-deck">${escape(post.excerpt)}</p>
        <ul class="article-tags" aria-label="文章标签">${post.tags.map(tag => `<li>${escape(tag)}</li>`).join('')}</ul>
        ${post.demo ? '<p class="demo-notice">这是一篇用于预览版式的示例文章，不代表作者的真实经历或正式发布内容。</p>' : ''}
      </header>
      <div class="article-layout">
        <article class="article-body" aria-label="文章正文">
          ${post.sections.map(section => `<section class="article-section" aria-labelledby="${section.id}"><h2 id="${section.id}">${escape(section.title)}</h2>${section.blocks.map(renderBlock).join('\n')}</section>`).join('\n')}
          <div class="article-end"><span aria-hidden="true">✦</span><p>本文完。谢谢你的阅读。</p></div>
        </article>
        <aside class="article-toc" aria-label="文章目录">
          <p class="toc-label">本文目录</p>
          <nav><ol>${post.sections.map(section => `<li><a data-toc-link href="#${section.id}">${escape(section.title)}</a></li>`).join('')}</ol></nav>
          <div class="article-tools"><button class="copy-link" type="button" hidden>复制文章链接 <span aria-hidden="true">↗</span></button><p class="copy-status" role="status" aria-live="polite"></p></div>
        </aside>
      </div>
      <nav class="article-pagination" aria-label="其他文章">${postLink(newer, 'article-prev', '上一篇', '←')}${postLink(older, 'article-next', '下一篇', '→')}</nav>
    </main>
    ${siteFooter('../')}
  </body>
</html>
`;
}

function render404() {
  return `<!doctype html>
${generated}
<html lang="zh-CN">
  <head>
    ${documentHead({ title: '404 · 这一页暂时偏离了轨道', description: '你寻找的页面没有找到，回到 Gudu 的博客继续探索。', canonical: `${site}/404.html`, prefix: '/', noindex: true })}
  </head>
  <body class="not-found-page">
    ${siteHeader('/')}
    <main class="not-found" id="main-content" tabindex="-1"><p class="eyebrow">LOST IN SPACE</p><p class="error-code" aria-hidden="true">404<span>.</span></p><h1>这一页，偏离了轨道。</h1><p>链接可能已经改变，或这段故事还没有写下。<br />回到熟悉的坐标，继续探索。</p><a class="text-link" href="/index.html#journal">返回文章列表 <span aria-hidden="true">↗</span></a></main>
    ${siteFooter('/')}
  </body>
</html>
`;
}

function renderFeed(posts) {
  const published = posts.filter(post => !post.demo);
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom"><channel>
<title>Gudu 的个人博客</title><link>${site}/</link><description>在自己的轨道上，记录技术、生活与思考。正式文章发布后会出现在此订阅中。</description><language>zh-CN</language>
<atom:link href="${site}/feed.xml" rel="self" type="application/rss+xml" />
${published.map(post => `<item><title>${escape(post.title)}</title><link>${postURL(post)}</link><guid isPermaLink="true">${postURL(post)}</guid><description>${escape(post.excerpt)}</description><pubDate>${new Date(`${post.date}T00:00:00Z`).toUTCString()}</pubDate><category>${escape(post.category)}</category></item>`).join('\n')}
</channel></rss>
`;
}

const journalEmpty = '<div class="journal-empty"><span class="empty-orbit" aria-hidden="true"></span><p class="empty-kicker">THE NEXT CHAPTER</p><h3>文章正在酝酿</h3><p>关于技术、生活与思考的记录，会陆续出现在这里。</p><a href="#about" class="text-link">先认识一下我 <span aria-hidden="true">↗</span></a></div>';
const archiveEmpty = '<p class="archive-empty">这里将按时间，收好每一篇文章。<span>第一篇，敬请期待。</span></p>';

function renderCards(posts) {
  if (!posts.length) return journalEmpty;
  return posts.map((post, i) => `<article class="post-card" data-category="${escape(post.category)}" style="--card-index: ${i}"><span class="post-number" aria-hidden="true">${String(i + 1).padStart(2, '0')}</span><div class="post-card-body"><div class="post-card-meta"><span class="post-category">${escape(post.category)}</span><time datetime="${post.date}">${displayDate(post.date)}</time><span class="post-reading-time">${post.readingMinutes} 分钟阅读</span>${post.demo ? '<span class="demo-label">示例</span>' : ''}</div><h3 class="post-title"><a href="${post.url}">${escape(post.title)}</a></h3><p class="post-summary">${escape(post.excerpt)}</p><div class="post-card-footer"><ul class="post-tags">${post.tags.map(tag => `<li>#${escape(tag)}</li>`).join('')}</ul><a class="post-link" href="${post.url}" aria-label="阅读全文：${escape(post.title)}">阅读全文 <span aria-hidden="true">↗</span></a></div></div></article>`).join('\n');
}

function renderArchive(posts) {
  if (!posts.length) return archiveEmpty;
  const years = [...new Set(posts.map(post => post.date.slice(0, 4)))];
  return years.map(year => `<section class="archive-year"><h3>${year}</h3><ol>${posts.filter(post => post.date.startsWith(year)).map(post => `<li><a href="${post.url}"><time datetime="${post.date}">${post.date.slice(5).replace('-', '.')}</time><span class="archive-title">${escape(post.title)}</span><span class="archive-category">${escape(post.category)}${post.demo ? ' · 示例' : ''}</span><span aria-hidden="true">↗</span></a></li>`).join('')}</ol></section>`).join('\n');
}

function replaceRegion(html, key, content) {
  const pattern = new RegExp(`(<!-- ${key}:start -->)[\\s\\S]*?(<!-- ${key}:end -->)`);
  if (!pattern.test(html)) throw new Error(`index.html 缺少 <!-- ${key}:start --> / <!-- ${key}:end --> 标记。`);
  return html.replace(pattern, (_, start, end) => `${start}\n${content}\n${end}`);
}

export async function buildBlog({ root = defaultRoot, checkOnly = false } = {}) {
  const sourceDirectory = resolve(root, 'content/posts');
  const postDirectory = resolve(root, 'posts');
  const filenames = (await readdir(sourceDirectory)).filter(name => name.endsWith('.json')).sort();
  const sources = await Promise.all(filenames.map(async filename => normalizePost(JSON.parse(await readFile(resolve(sourceDirectory, filename), 'utf8')), filename)));
  const slugs = new Set();
  for (const post of sources) {
    if (slugs.has(post.slug)) throw new Error(`重复的文章 slug：${post.slug}`);
    slugs.add(post.slug);
  }
  const posts = sources.filter(post => !post.draft).sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
  const metadata = posts.map(({ sections, draft, ...post }) => post);
  const artifacts = new Map();
  artifacts.set('js/posts-data.js', `// Generated by scripts/build-blog.mjs. Do not edit directly.\nwindow.BLOG_POSTS = ${jsonForHTML(metadata)};\n`);
  for (const [index, post] of posts.entries()) artifacts.set(`posts/${post.slug}.html`, renderArticle(post, index, posts));
  artifacts.set('feed.xml', renderFeed(posts));
  artifacts.set('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${site}/</loc></url>${posts.filter(post => !post.demo).map(post => `<url><loc>${postURL(post)}</loc><lastmod>${post.date}</lastmod></url>`).join('')}</urlset>\n`);
  artifacts.set('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`);
  artifacts.set('404.html', render404().replace(/[ \t]+$/gm, ''));
  let homepage = await readFile(resolve(root, 'index.html'), 'utf8');
  homepage = replaceRegion(homepage, 'posts', renderCards(posts));
  homepage = replaceRegion(homepage, 'archive', renderArchive(posts));
  artifacts.set('index.html', homepage);

  const stale = [];
  const existing = await readdir(postDirectory).catch(error => { if (error.code === 'ENOENT') return []; throw error; });
  for (const filename of existing.filter(name => name.endsWith('.html'))) {
    const path = resolve(postDirectory, filename);
    if (dirname(path) !== postDirectory || artifacts.has(`posts/${filename}`)) continue;
    if ((await readFile(path, 'utf8')).includes(generated)) stale.push(path);
  }

  if (checkOnly) {
    const outdated = [];
    for (const [filename, content] of artifacts) {
      const actual = await readFile(resolve(root, filename), 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
      if (actual !== content) outdated.push(filename);
    }
    if (outdated.length || stale.length) throw new Error(`生成文件需要更新，请运行 npm run build：${[...outdated, ...stale].join(', ')}`);
    console.log(`Blog checked: ${posts.length} published article(s); generated files are current.`);
    return;
  }

  for (const [filename, content] of artifacts) {
    const path = resolve(root, filename);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, 'utf8');
  }
  for (const path of stale) await unlink(path);
  console.log(`Blog built: ${posts.length} published article(s), ${sources.length - posts.length} draft(s).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildBlog({ checkOnly: process.argv.includes('--check') }).catch(error => {
    console.error(`Blog build failed: ${error.message}`);
    process.exitCode = 1;
  });
}
